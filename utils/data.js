function tideAdvice(day) {
  const d = Number(day);
  if (!d) return null;
  const big = (d >= 1 && d <= 4) || (d >= 16 && d <= 18);
  const small = (d >= 9 && d <= 11) || (d >= 24 && d <= 26);
  if (big) {
    return {
      title: '大潮窗口（经验判断）',
      text: '农历' + day + '日通常属大潮期，潮差较大。退潮前约 1 小时至退潮后 1—2 小时适合滩涂活动；涨潮时饵料鱼靠岸，岸钓机会较多。'
    };
  }
  if (small) {
    return {
      title: '小潮窗口（经验判断）',
      text: '农历' + day + '日通常潮差较小、水流偏缓。滩涂裸露范围有限，可尝试礁石边与潮沟，整体窗口短于大潮。'
    };
  }
  return {
    title: '中潮窗口（经验判断）',
    text: '农历' + day + '日属中大潮之间，仍可出钓。建议把重点放在晨昏时段，并结合当日实际潮时调整。'
  };
}

